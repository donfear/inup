// Bundle the CLI into one file, after tsc has written dist/.
//
//   node scripts/build-cli.mjs   (part of `pnpm build`)
//
// tsc's CommonJS output makes `inup` resolve, read and compile 90 modules before
// it can print --version, and ~230 for a --json run (semver and yaml alone are
// over 100). The bundle is one file, so dist/cli.js becomes a launcher: it turns
// on V8's compile cache first, so the bundle's bytecode is reused across runs
// too, then starts the bundled CLI.
//
// The rest of dist/ stays tsc output: the public API (`main`), and the tooling
// that loads single modules from it (pnpm bench, publish-native.mjs,
// verify-native.sh). The bundle carries its own copy of every module, so it
// never loads them. The native addon stays outside: rust-core.ts requires it
// from a computed path at runtime.
import { chmodSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

export const BUNDLE_FILE = 'cli.bundle.js'

/** dist/cli.js: compile cache on before the bundle compiles, then run the CLI. */
export const LAUNCHER = `#!/usr/bin/env node
'use strict'
// Generated by scripts/build-cli.mjs. Turns on V8's compile cache before the
// bundled CLI compiles, so later runs reuse its bytecode as well.
try {
  require('node:module').enableCompileCache?.()
} catch {
  /* best-effort */
}
// Exports what tsc's cli.js did; only a run as the program parses its arguments.
const cli = require('./${BUNDLE_FILE}')
module.exports = cli
if (require.main === module) cli.program.parse()
`

/** Write the bundle and its launcher into `outdir`; returns the launcher's path. */
export async function bundleCli({ outdir = 'dist', entry = 'src/cli.ts' } = {}) {
  const { warnings } = await build({
    // decode-pool.ts starts its workers from decode-worker.js beside the code that runs it.
    entryPoints: [
      { in: entry, out: BUNDLE_FILE.replace(/\.js$/, '') },
      { in: 'src/shared/registry/decode-worker.ts', out: 'decode-worker' },
    ],
    outdir,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22.19',
    // Whitespace and syntax only: function and class names stay readable in stack traces.
    minifyWhitespace: true,
    minifySyntax: true,
    sourcemap: true,
    logLevel: 'warning',
  })
  // A warning here (a dynamic require, import.meta in a dependency) is code that would
  // break or behave differently once bundled: fail the build instead of shipping it.
  if (warnings.length > 0) throw new Error(`esbuild reported ${warnings.length} warning(s)`)
  const launcher = join(outdir, 'cli.js')
  writeFileSync(launcher, LAUNCHER)
  chmodSync(launcher, 0o755)
  // tsc's map of the cli.js the launcher replaced.
  rmSync(`${launcher}.map`, { force: true })
  return launcher
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  bundleCli().catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
