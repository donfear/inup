import { lstatSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { writeFileAtomic } from '../fs/write-atomic'
import { PACKAGE_NAME, PACKAGE_VERSION } from './package-meta'
import { findConfigFilesIn } from './project-config'

/** The file `--init` writes; first in the loader's lookup order. */
export const INIT_CONFIG_FILENAME = `${PACKAGE_NAME}.config.jsonc`

/**
 * Where editors fetch config-schema.json for `version`, as the template's "$schema".
 * A release points at its major version, so the URL keeps working and picks up fields
 * added in later minor releases. A prerelease points at itself: the `@2` range would
 * not match 2.0.0-rc.1 and would 404 until 2.0.0 ships.
 */
export function schemaUrl(version: string): string {
  const tag = version.includes('-') ? version : version.split('.')[0]
  return `https://cdn.jsdelivr.net/npm/${PACKAGE_NAME}@${tag}/config-schema.json`
}

/**
 * `--init`'s write: a fresh template at <cwd>/inup.config.jsonc, and every other config
 * file in `cwd` deleted, so the directory ends up with exactly one and no stale copy is
 * left to edit by mistake. Comments only belong in a .jsonc file, which is why an old
 * inup.config.json is replaced rather than overwritten in place.
 *
 * Refuses, touching nothing, when a config path in `cwd` is not a plain file. Writes
 * before deleting, so a failed write leaves the old config where it was.
 */
export function writeInitConfig(cwd: string): { path: string; removed: string[] } {
  const target = join(cwd, INIT_CONFIG_FILENAME)
  const existing = findConfigFilesIn(cwd)
  for (const path of existing) {
    if (!lstatSync(path).isFile()) {
      throw new Error(`${path} is not a regular file; move it aside and run inup --init again`)
    }
  }
  writeFileAtomic(target, buildConfigTemplate())
  const removed = existing.filter((path) => path !== target)
  for (const path of removed) rmSync(path)
  return { path: target, removed }
}

/**
 * A fully commented starter config documenting every supported field, with the
 * "$schema" that gives editors autocomplete and checking.
 * Comments and trailing commas are legal here — the loader strips both before
 * JSON.parse — so every field ends in a comma, and deleting the `//` of any
 * commented-out field enables it, in any combination.
 */
export function buildConfigTemplate(): string {
  return `// ${INIT_CONFIG_FILENAME} — generated by ${PACKAGE_NAME} v${PACKAGE_VERSION}
// Docs: https://github.com/donfear/${PACKAGE_NAME}/blob/main/docs/guide/configuration.md
// Comments and trailing commas are allowed in this file; every field is optional.
{
  // Lets editors such as VS Code autocomplete and check this file.
  "$schema": "${schemaUrl(PACKAGE_VERSION)}",

  // Hide packages from upgrade checks entirely.
  // Exact names or globs: "lodash", "@babel/*", "eslint-*" (? matches one char).
  "ignore": [],

  // Check only these packages, as if every run named them on the command
  // line (\`inup react\`). Same pattern syntax as "ignore". Packages named on
  // the command line replace this list for that run.
  // "only": ["@myco/*"],

  // Suppress only MAJOR updates for these packages — minor/patch bumps still
  // show, and a package whose only update is a new major counts as up to date.
  // Same pattern syntax as "ignore".
  "ignoreMajor": [],

  // Skip directories while discovering package.json files (regex patterns).
  "exclude": [],

  // Scan these directory names even though they are on the default skip list
  // (node_modules, dist, build, coverage, out, lib, es, esm, cjs).
  "scanDirs": [],

  // Show vulnerability badges for peerDependencies / optionalDependencies.
  // Both default to false so that risk stays hidden unless you opt in.
  "showPeerDependencyVulnerabilities": false,
  "showOptionalDependencyVulnerabilities": false,

  // Supply-chain cooldown, in MINUTES: never offer a version published more
  // recently than this. Freshly published versions are the ones most likely to
  // be a compromised release nobody has caught yet. 10080 = 7 days.
  // Enabling it fetches the full registry metadata, so the first run is a
  // little slower; later runs are cushioned by the ETag cache.
  // "minimumReleaseAge": 10080,

  // Packages exempt from the cooldown — typically your own, which you want
  // immediately. Same pattern syntax as "ignore".
  // "minimumReleaseAgeExclude": ["@myco/*"],

  // Pin registry-fetch parallelism (integer 1-24) and disable adaptive
  // ramping — an escape hatch for slow or metered connections.
  // "concurrency": 4,

  // inup fetches and parses registry data with its native (Rust) core. The
  // first run downloads the prebuilt core for this platform once (about
  // 1.5 MB, verified against the registry's checksum). Set false to keep
  // native code off this project.
  // "native": false,

  // A command your upgrades must keep passing, usually your tests. After you
  // upgrade in the picker or with --apply, inup runs it and puts back each
  // upgrade it fails with. --no-verify skips it for one run.
  // "verify": "npm test",
}
`
}
